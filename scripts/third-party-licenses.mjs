/**
 * Writes THIRD_PARTY_LICENSES.md from `pnpm licenses list --prod --json`, and fails if a
 * production dependency carries a copyleft licence that isn't on the allowlist.
 * Usage: `pnpm licenses:write` (writes the file) or `pnpm licenses:check` (CI, no write).
 */
import { execSync } from "node:child_process";
import { readFile, writeFile } from "node:fs/promises";

import { format } from "prettier";

const COPYLEFT = /\b(A?GPL|LGPL|SSPL|EUPL|MPL)\b/i;
/** Copyleft packages accepted after review, by name. Empty on purpose. */
const ALLOWLIST = new Set([]);

// A single command string: pnpm is a .cmd shim on Windows, so it needs a shell.
const raw = execSync("pnpm licenses list --prod --json", { encoding: "utf8" });
const byLicense = JSON.parse(raw);

const packages = Object.entries(byLicense)
  .flatMap(([license, entries]) =>
    entries.map((entry) => ({
      name: entry.name,
      versions: entry.versions.join(", "),
      license,
      homepage: entry.homepage ?? "",
    })),
  )
  .sort((a, b) => a.name.localeCompare(b.name));

const blocked = packages.filter((pkg) => COPYLEFT.test(pkg.license) && !ALLOWLIST.has(pkg.name));
if (blocked.length > 0) {
  console.error("Copyleft licences in production dependencies:");
  for (const pkg of blocked) console.error(`  ${pkg.name} (${pkg.license})`);
  process.exit(1);
}

const lines = [
  "# Third-party licences",
  "",
  "Production dependencies of this site and their licences, generated by `pnpm licenses:write` from `pnpm licenses list --prod`. Do not edit by hand.",
  "",
  "| Package | Version | Licence |",
  "| --- | --- | --- |",
  ...packages.map((pkg) => {
    const name = pkg.homepage ? `[${pkg.name}](${pkg.homepage})` : pkg.name;
    return `| ${name} | ${pkg.versions} | ${pkg.license} |`;
  }),
  "",
];
// Formatted like every other Markdown file, so `pnpm format` never makes the check fail.
const output = await format(lines.join("\n"), { parser: "markdown" });

if (process.argv.includes("--check")) {
  const current = await readFile("THIRD_PARTY_LICENSES.md", "utf8").catch(() => "");
  if (current !== output) {
    console.error("THIRD_PARTY_LICENSES.md is out of date: run `pnpm licenses:write`.");
    process.exit(1);
  }
  console.log(`Licences OK (${String(packages.length)} production packages).`);
} else {
  await writeFile("THIRD_PARTY_LICENSES.md", output);
  console.log(`THIRD_PARTY_LICENSES.md written (${String(packages.length)} packages).`);
}
